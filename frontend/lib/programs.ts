/**
 * แปลงรายการหลักสูตรจาก API ให้พร้อมแสดงบนหน้าเว็บ
 *
 * แยกออกมาเป็นฟังก์ชันล้วนเพื่อทดสอบได้โดยไม่ต้อง render อะไรเลย และเพราะหน้าอื่น
 * ที่ต้องแสดงรายชื่อหลักสูตรก็ต้องใช้ตรรกะเดียวกันนี้
 */
import type { Course } from "@/lib/types";

/**
 * ชื่อสาขาสั้นๆ จากชื่อเต็มในเอกสาร
 *
 * ห้ามใช้รูปแบบทั่วไปอย่าง /^หลักสูตร\S*บัณฑิต/ เพื่อตัดชื่อปริญญา เพราะภาษาไทย
 * ไม่มีช่องว่างระหว่างคำ \S* จึงกลืนไปทั้งชื่อจนเหลือสตริงว่าง — "หลักสูตรการแพทย์
 * แผนไทยประยุกต์บัณฑิต" หายทั้งชื่อ (ฝั่ง backend เคยเจอปัญหาเดียวกันใน
 * services/tuition.py)
 */
export function shortTitle(fullTitle: string): string {
  const noYear = fullTitle.replace(/\s*\(พ\.ศ\.\s*\d{4}\)\s*/g, "").trim();
  // รูปแบบปกติคือ "หลักสูตร<ชื่อปริญญา> สาขาวิชา<ชื่อสาขา>" จึงเอาส่วนหลังคำว่าสาขาวิชา
  if (noYear.includes("สาขาวิชา")) return noYear.split("สาขาวิชา").pop()!.trim();
  // บางหลักสูตรไม่มีคำว่า "สาขาวิชา" เลย เพราะชื่อสาขากับชื่อปริญญาเป็นคำเดียวกัน
  return noYear.replace(/^หลักสูตร\s*/, "").replace(/บัณฑิต$/, "").trim();
}

/** ปี พ.ศ. ที่อยู่ท้ายชื่อ — 0 เมื่อไม่ระบุ ใช้เทียบว่าฉบับไหนใหม่กว่า */
export function editionYear(fullTitle: string): number {
  const m = fullTitle.match(/\(พ\.ศ\.\s*(\d{4})\)/);
  return m ? Number(m[1]) : 0;
}

/**
 * เหลือหลักสูตรละหนึ่งรายการ โดยเก็บฉบับปรับปรุงล่าสุดไว้
 *
 * คลังเอกสารมี 18 รายการแต่มีแค่ 14 หลักสูตร เพราะสี่หลักสูตรมีทั้งฉบับเดิมและฉบับ
 * ปรับปรุง ถ้าเอามาแสดงดิบๆ ผู้ใช้จะเห็นชื่อซ้ำกันสองใบติดกันโดยไม่รู้ว่าต่างกันตรงไหน
 * และเผลอเอาสองฉบับของหลักสูตรเดียวกันไปเปรียบเทียบกันเอง
 *
 * เทียบด้วยชื่อที่ตัดปีออกแล้ว ไม่ใช่ id เพราะสองฉบับเป็นคนละแถวในฐานข้อมูล
 */
export function latestEditions(courses: Course[]): Course[] {
  const best = new Map<string, Course>();
  for (const c of courses) {
    const key = shortTitle(c.title);
    const seen = best.get(key);
    if (!seen || editionYear(c.title) > editionYear(seen.title)) best.set(key, c);
  }
  return [...best.values()];
}
