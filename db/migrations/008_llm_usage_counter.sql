BEGIN;

-- ---------------------------------------------------------------------
-- ตารางนับ
--
-- คีย์หลักเป็น (วัน, เหตุการณ์) เพื่อให้การนับเป็น UPSERT ก้อนเดียว ไม่ใช่การเพิ่มแถว
-- ทุกครั้งที่มีคำถาม — หนึ่งวันมีไม่เกินจำนวนชนิดเหตุการณ์ ตารางจึงโตช้ามาก
-- (ประมาณ 10 แถวต่อวัน = ราว 3,650 แถวต่อปี)
--
-- `day` เป็น DATE ตามเวลาประเทศไทย ฝั่งแอปเป็นผู้คำนวณแล้วส่งมา ไม่ใช่ now() ของ
-- ฐานข้อมูลซึ่งเป็น UTC — ถ้าใช้ UTC เส้นแบ่งวันจะอยู่ที่ 7 โมงเช้าของไทย ซึ่งอ่านยาก
-- เวลาเทียบกับสิ่งที่เกิดขึ้นในวันนั้นจริง ๆ
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.llm_usage_daily (
    day        DATE NOT NULL,
    event      TEXT NOT NULL,
    n          BIGINT NOT NULL DEFAULT 0 CHECK (n >= 0),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (day, event)
);

-- ---------------------------------------------------------------------
-- สิทธิ์ของ role
--
-- advisor_api ต้อง INSERT และ UPDATE ได้ เพราะการนับเป็น
-- `insert … on conflict do update` · ไม่ให้ DELETE เพราะตัวนับมีแต่เพิ่ม
-- การล้างข้อมูลเก่าเป็นงานของผู้ดูแลที่ใช้สิทธิ์สูงกว่า
--
-- advisor_ingest และ advisor_web ไม่ได้สิทธิ์ใด ๆ โดยตั้งใจ — ทั้งคู่ไม่เรียกโมเดล
-- ---------------------------------------------------------------------
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'advisor_api') THEN
        GRANT SELECT, INSERT, UPDATE ON public.llm_usage_daily TO advisor_api;
    END IF;
END;
$$;

INSERT INTO mko.schema_migrations (version) VALUES ('008_llm_usage_counter')
    ON CONFLICT (version) DO NOTHING;

COMMIT;

