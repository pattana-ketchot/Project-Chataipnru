"""
ตอบคำทักทาย/ขอบคุณ/คำถามว่าเป็นใคร ก่อนเข้าสู่ขั้นตอนค้นเอกสาร

ทำไมต้องแยกออกมา: ข้อความอย่าง "สวัสดีครับ" ไม่มีเนื้อหาให้ค้นเจอในเอกสาร
หลักสูตร คะแนนความใกล้เคียงจึงต่ำ (วัดได้ 0.477-0.556) และตกเกณฑ์ 0.58 กลาย
เป็นถูกปฏิเสธด้วยข้อความ "ผมตอบได้เฉพาะเรื่องหลักสูตร" ซึ่งเป็นสิ่งแรกที่ผู้ใช้
เจอเมื่อเปิดแชตขึ้นมาแล้วทักทาย

ตอบจากข้อความสำเร็จรูปโดยไม่เรียก LLM เพราะ:
  - ตอบทันที ไม่ต้องรอ 10 วินาทีเหมือนคำถามจริง
  - คุมถ้อยคำได้แน่นอน ไม่มีโอกาสที่โมเดลจะพูดนอกบทบาท
  - ถือโอกาสบอกผู้ใช้ว่าถามอะไรได้บ้าง ซึ่งช่วยลดคำถามนอกขอบเขตตั้งแต่ต้น
"""
from __future__ import annotations

import re

# คำลงท้ายสุภาพ ตัดออกก่อนเทียบ เพื่อให้ "สวัสดีครับ" ตรงกับ "สวัสดี"
_POLITE_TAIL = re.compile(r"(ครับผม|ครับ|ค่ะ|คะ|ค่า|จ้า|จ้ะ|จ๊ะ|นะ|น่ะ|ฮะ|ฮ่ะ)+[\s!?.]*$")

# ต้องเทียบแบบ "ทั้งข้อความ" ไม่ใช่ substring ไม่งั้น "สวัสดีครับ อยากถามเรื่อง
# หลักสูตรวิทคอม" จะถูกดักเป็นคำทักทายแล้วคำถามจริงหายไป
_GREETING = {"สวัสดี", "หวัดดี", "วัสดี", "ดี", "hello", "hi", "hey", "yo", "สวัสดีตอนเช้า", "อรุณสวัสดิ์"}
_THANKS = {"ขอบคุณ", "ขอบใจ", "ขอบคุณมาก", "thank you", "thanks", "thank", "thx"}
_BYE = {"ลาก่อน", "บาย", "บายๆ", "bye", "goodbye", "ไปก่อน", "ไปละ", "แค่นี้"}

# คำถามว่าเป็นใคร/ทำอะไรได้ — เทียบแบบมีคำนี้อยู่ในข้อความได้ เพราะสำนวนหลากหลาย
# แต่จำกัดความยาวไว้เพื่อไม่ให้ไปกินคำถามจริงที่ยาวกว่า
# "ต้องถามยังไงถึงจะตอบได้" มาจากผู้ใช้จริงที่โดนปฏิเสธติดกันหลายครั้งแล้วพยายาม
# หาวิธีถามให้ถูก — ถ้าปฏิเสธคำถามนี้ซ้ำอีกผู้ใช้จะไปต่อไม่ถูกเลย
_IDENTITY_HINTS = (
    "คุณคือใคร", "คุณเป็นใคร", "เธอคือใคร", "นี่คืออะไร", "ระบบนี้คืออะไร",
    "ทำอะไรได้บ้าง", "ช่วยอะไรได้บ้าง", "ช่วยอะไรได้", "ใช้งานยังไง", "ใช้ยังไง",
    "ถามอะไรได้บ้าง", "ถามอะไรได้", "ต้องถามยังไง", "ถามยังไง", "ถามแบบไหน", "ตอบอะไรได้บ้าง",
)

_MAX_CHARS = 40  # คำถามจริงมักยาวกว่านี้

_CAPABILITY_BLURB = (
    "ผมเป็นผู้ช่วยตอบคำถามเรื่องหลักสูตรของคณะครับ ตอบจากเอกสารหลักสูตร (มคอ.2) จริง "
    "ถามได้เช่น หลักสูตรไหนเรียนอะไรบ้าง ต้องเรียนกี่หน่วยกิต หรือจบไปทำงานอะไรได้"
)

_REPLIES = {
    "greeting": "สวัสดีครับ 👋 " + _CAPABILITY_BLURB,
    "thanks": "ยินดีครับ ถ้ามีอะไรอยากรู้เพิ่มเติมเกี่ยวกับหลักสูตร ถามได้เลยครับ",
    "bye": "ขอบคุณที่ใช้บริการครับ ขอให้โชคดีกับการเลือกหลักสูตรนะครับ",
    "identity": _CAPABILITY_BLURB,
}


def match_small_talk(message: str) -> str | None:
    """คืนข้อความตอบกลับถ้าเป็นการทักทาย/ขอบคุณ/ถามตัวตน มิฉะนั้นคืน None"""
    text = message.strip().lower()
    if not text or len(text) > _MAX_CHARS:
        return None

    core = _POLITE_TAIL.sub("", text).strip(" \t!?.,ๆ")

    if core in _GREETING:
        return _REPLIES["greeting"]
    if core in _THANKS:
        return _REPLIES["thanks"]
    if core in _BYE:
        return _REPLIES["bye"]
    if any(h in text for h in _IDENTITY_HINTS):
        return _REPLIES["identity"]
    return None
