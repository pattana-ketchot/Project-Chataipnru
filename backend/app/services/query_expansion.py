"""
ขยายคำย่อ/คำเรียกติดปากให้เป็นชื่อหลักสูตรเต็มก่อนนำไปค้นหา

ทำไมต้องมี: เอกสาร มคอ.2 ใช้ชื่อทางการเสมอ ("วิทยาการคอมพิวเตอร์") แต่ผู้ใช้จริง
พิมพ์คำย่อ ("วิทคอม") ซึ่ง embedding จับคู่กันไม่ติด วัดจากคลังจริง:

    "จบวิทคอมล่ะไปสายงานไหนได้บ้าง"        -> 0.531  ตกเกณฑ์ 0.58 ถูกปฏิเสธ
    "จบวิทยาการคอมพิวเตอร์ทำงานอะไรได้บ้าง" -> 0.720  ผ่านสบาย

คำถามสองอันนี้ถามเรื่องเดียวกัน แต่ระบบตอบได้อันเดียว

วิธีทำ: "เติม" ชื่อเต็มต่อท้ายคำถาม ไม่ใช่ "แทนที่" คำย่อ เพื่อให้ถ้อยคำเดิมของ
ผู้ใช้ยังมีน้ำหนักในเวกเตอร์อยู่ และถ้าเดาผิดก็ไม่ได้ลบเจตนาเดิมทิ้ง

ข้อจำกัด: เป็นตารางที่เขียนมือเฉพาะหลักสูตรของคณะนี้ ถ้าเพิ่มหลักสูตรใหม่ต้องมา
เติมเอง — ทางเลือกที่ขยายได้กว่าคือสร้าง embedding ของชื่อหลักสูตรทุกอันแล้วหา
ตัวที่ใกล้ที่สุดกับคำถาม แต่แลกกับความซับซ้อนและเวลาที่เพิ่มขึ้นต่อคำถาม
"""
from __future__ import annotations

# คำย่อ/คำเรียกติดปาก -> ชื่อสาขาตามเอกสาร
# key ต้องเป็นคำที่เจาะจงพอจะไม่ไปตรงกับคำอื่นโดยบังเอิญ
_ALIASES: dict[str, str] = {
    "วิทคอม": "วิทยาการคอมพิวเตอร์",
    "คอมพิวเตอร์ไซแอนซ์": "วิทยาการคอมพิวเตอร์",
    "ไอที": "เทคโนโลยีสารสนเทศ",
    "it": "เทคโนโลยีสารสนเทศ",
    "แอนิเมชัน": "คอมพิวเตอร์แอนิเมชันและมัลติมีเดีย",
    "แอนิเมชั่น": "คอมพิวเตอร์แอนิเมชันและมัลติมีเดีย",
    "อนิเมชั่น": "คอมพิวเตอร์แอนิเมชันและมัลติมีเดีย",
    "แพทย์แผนไทย": "การแพทย์แผนไทยประยุกต์",
    "หมอนวด": "การแพทย์แผนไทยประยุกต์",
    "คหกรรม": "คหกรรมศาสตร์",
    "เครื่องสำอาง": "วิทยาศาสตร์เครื่องสำอาง",
    "สิ่งแวดล้อม": "วิทยาศาสตร์และเทคโนโลยีสิ่งแวดล้อม การจัดการสิ่งแวดล้อมและทรัพยากรธรรมชาติ",
    "คณิต": "คณิตศาสตร์",
    "เกษตร": "การจัดการเทคโนโลยีการเกษตรสมัยใหม่",
    "ชีวภาพ": "เทคโนโลยีผลิตภัณฑ์ชีวภาพกับการประกอบธุรกิจ",
    "สุขภาพ": "เทคโนโลยีการจัดการสุขภาพ",
}


def expand_query(query: str) -> str:
    """เติมชื่อหลักสูตรเต็มต่อท้ายถ้าพบคำย่อ คืนข้อความเดิมถ้าไม่พบ"""
    lowered = query.lower()
    additions: list[str] = []
    for alias, full in _ALIASES.items():
        if alias in lowered and full not in query and full not in " ".join(additions):
            additions.append(full)
    return f"{query} {' '.join(additions)}" if additions else query
