# ทุกคำถามมีช่องว่างหลังกลุ่มที่เกี่ยวข้องจริงเสมอ และช่องว่างนั้นกว้างกว่าระยะห่าง
# ภายในกลุ่ม ค่า .04 จึงอยู่ระหว่างสองระยะนี้ ไม่ใช่ค่าที่ปรับให้พอดีกับตัวอย่างใด
#
# ผลคือจำนวนสาขาที่แนะนำเป็นไปตามข้อมูล ไม่ใช่ตัวเลขคงที่ — คำถามที่มีหลายสาขาตอบได้
# ก็ได้หลายสาขา คำถามที่มีสาขาเดียวตรงจริงก็ได้สาขาเดียว
_RELEVANCE_MARGIN = 0.04


def _close_to_best(scored: list[dict]) -> list[dict]:
    """
    เหลือเฉพาะหลักสูตรที่คะแนนใกล้เคียงอันดับหนึ่งพอจะเรียกว่าเกี่ยวข้องเหมือนกัน

    เดิมส่งสามอันดับแรกให้เสมอ ซึ่งแปลว่าถ้ามีสาขาเดียวที่เกี่ยวข้องจริง อันดับ 2 และ 3
    จะเป็นสาขาที่บังเอิญมีคำที่ตรงกันอยู่ในเอกสาร เช่น "ชอบทำงานกับคอมพิวเตอร์" เคยได้
    การประกอบอาหารและการบริการอาหารติดมาด้วย เพราะหลักสูตรนั้นมีวิชาการใช้คอมพิวเตอร์
    ในงานบริการอาหาร — คอมพิวเตอร์เป็นเครื่องมือของหลักสูตรนั้น ไม่ใช่แก่นของมัน

    การวัดด้วยคะแนนแยกสองอย่างนี้ออกจากกันได้ เพราะหลักสูตรที่มีแก่นตรงกับคำถามจะได้
    คะแนนสูงทั้งจากเนื้อหาและจากชื่อหลักสูตร ส่วนหลักสูตรที่แค่เอ่ยถึงจะได้คะแนนจาก
    เนื้อหาบางส่วนเท่านั้น
    """
    if not scored:
        return scored
    floor = scored[0]["score"] - _RELEVANCE_MARGIN
    return [s for s in scored if s["score"] >= floor]


def confidence_of(matches: list[ProgramMatch]) -> str:
    """
    บอกว่าผลลัพธ์ชุดนี้ควรเชื่ออันดับ 1 ได้แค่ไหน คืน "high" หรือ "low"

    ใช้ช่องว่างระหว่างอันดับ 1 กับอันดับ 3 เป็นตัวชี้วัด ซึ่งวัดแล้วพบว่าแยกสองกรณี
    ออกจากกันได้จริง (eval/match_eval.py, 25 โปรไฟล์)

        ข้อที่ระบบตอบถูก   ห่างเฉลี่ย 13.9 จุด
        ข้อที่ระบบตอบผิด   ห่างเฉลี่ย  9.6 จุด

    เมื่อผลลัพธ์เกาะกลุ่มกัน โอกาสที่อันดับ 1 จะไม่ใช่คำตอบที่ผู้ใช้ต้องการสูงขึ้นชัดเจน
    หน้าเว็บจึงควรเปลี่ยนไปชวนให้ดูหลายตัวเลือกแทนการชูอันดับ 1 อย่างเดียว

    ตั้งเกณฑ์ที่ 10 จุดซึ่งอยู่ระหว่างค่าเฉลี่ยทั้งสองกลุ่ม ไม่ใช่ค่าที่ปรับให้ได้ผลสวย
    ที่สุดกับชุดทดสอบ เพราะ 25 โปรไฟล์ยังน้อยเกินกว่าจะปรับละเอียดได้อย่างมีความหมาย
    """
    if len(matches) < 3:
        return "low"
    return "high" if matches[0].match_percent - matches[2].match_percent >= _CONFIDENCE_GAP else "low"


def _to_percent(score: float) -> int:
    ratio = (score - _PCT_FLOOR) / (_PCT_CEILING - _PCT_FLOOR)
    return max(0, min(100, round(ratio * 100)))


def _fetch_evidence(db: Session, chunk_ids: list[uuid.UUID]) -> str:
    rows = db.execute(
        text("SELECT page_number, content FROM course_chunks WHERE id = ANY(:ids)"),
        {"ids": chunk_ids},
    ).all()
    return "\n\n".join(f"[หน้า {r.page_number}]\n{r.content}" for r in rows)


def _title_vectors(db: Session, connector) -> dict[uuid.UUID, list[float]]:
    """
    เวกเตอร์ของ "ชื่อหลักสูตร" แต่ละเล่ม คำนวณครั้งเดียวแล้วเก็บไว้ใช้ซ้ำ

    มีหลักสูตรระดับปริญญาตรีไม่กี่สิบเล่ม การคำนวณครั้งแรกจึงใช้เวลาไม่ถึงสองวินาที
    และหลังจากนั้นไม่มีค่าใช้จ่ายอีกเลยตลอดอายุของโปรเซส
    """
    global _TITLE_CACHE
    if _TITLE_CACHE is None:
        rows = db.execute(text(f"SELECT id, title FROM courses c WHERE {_UNDERGRAD_ONLY}")).all()
        _TITLE_CACHE = {r.id: connector.embed(_distinctive_name(r.title)) for r in rows}
    return _TITLE_CACHE


def _cosine(a: list[float], b: list[float]) -> float:
    dot = sum(x * y for x, y in zip(a, b))
    na = sum(x * x for x in a) ** 0.5
    nb = sum(y * y for y in b) ** 0.5
    return dot / (na * nb) if na and nb else 0.0


def match_programs(
    db: Session,
    answers: dict,
    limit: int = MAX_RESULTS,
    relevant_only: bool = False,
) -> list[ProgramMatch]:
    """
    จัดอันดับหลักสูตรตามความใกล้เคียงกับสิ่งที่ผู้ใช้บอก

    relevant_only=True จะตัดหลักสูตรที่คะแนนห่างจากอันดับหนึ่งเกินเกณฑ์ออก ทำให้
    จำนวนที่คืนมาไม่คงที่ ใช้กับการตอบในแชทซึ่งไม่ควรเสนอสาขาที่แค่เกี่ยวข้องห่างๆ
    ส่วนหน้าแบบสอบถามยังคืนครบตามที่ขอ เพราะแสดงเปอร์เซ็นต์กำกับให้ผู้ใช้ชั่งเอง
    """
    connector = get_llm_connector()
    profile_text = build_profile_text(answers)
    query_text = build_match_query(answers)
    if not query_text.strip():
        raise ValueError("ต้องตอบอย่างน้อยหนึ่งข้อในหัวข้อวิชาที่ชอบ ความสนใจ หรือความถนัด")

    profile_vec = connector.embed(query_text)
    scored = score_all_programs(db, profile_vec)

    # ผสมความใกล้เคียงกับ "ชื่อหลักสูตร" เข้ากับความใกล้เคียงของเนื้อหา
    #
    # เนื้อหาอย่างเดียวแยกแยะได้ไม่ดีพอ เพราะเอกสาร มคอ.2 ทุกเล่มใช้ข้อความมาตรฐาน
    # ร่วมกันมาก (ชื่อมหาวิทยาลัย ชื่อคณะ หัวข้อตามแบบฟอร์ม เกณฑ์มาตรฐานหลักสูตร)
    # คะแนนของทุกหลักสูตรจึงกระจุกอยู่ในช่วงแคบราว 0.59-0.68 จนอันดับสลับกันได้ง่าย
    # ด้วยส่วนต่างเพียง 0.005
    #
    # ชื่อหลักสูตรเป็นสัญญาณที่แยกแยะได้ดีที่สุดและสั้นจนไม่มีอะไรเจือปน นักเรียนที่
    # ตอบว่าสนใจสิ่งแวดล้อมควรถูกจับคู่กับหลักสูตรที่ชื่อมีคำว่าสิ่งแวดล้อมตั้งแต่ต้น
    titles = _title_vectors(db, connector)
    for s in scored:
        s["score"] = (1 - _TITLE_WEIGHT) * s["score"] + _TITLE_WEIGHT * _cosine(
            profile_vec, titles[s["course_id"]]
        )
    scored.sort(key=lambda s: s["score"], reverse=True)

    # ตัดหลักสูตรที่คณะไม่ได้เปิดรับสมัครแล้วออกก่อนจัดอันดับให้ผู้ใช้เห็น
    #
    # คลังเก็บเอกสารของหลักสูตรที่เลิกรับสมัครไปแล้วไว้ด้วย ซึ่งถูกต้องสำหรับการตอบ
    # คำถามของนักศึกษาที่กำลังเรียนอยู่ แต่ผิดสำหรับการแนะนำที่เรียนให้คนที่ยังไม่ได้
    # สมัคร — เขาจะวางแผนไปสมัครในสิ่งที่ไม่มีอยู่แล้ว (ดู services/offered.py)
    scored = [s for s in scored if is_offered(s["title"])]
    scored = _collapse_editions(scored)
    if relevant_only:
        scored = _close_to_best(scored)
    scored = scored[:limit]

    # ขอเหตุผลทั้งชุดในการเรียกโมเดลครั้งเดียว ไม่ใช่หลักสูตรละครั้ง เพราะการเรียกทีละ
    # หลักสูตรทำให้ผู้ใช้รอเป็นจำนวนเท่าของหลักสูตรที่แนะนำ และเปลืองโควตาโดยไม่จำเป็น
    # ส่งเนื้อหาให้พอจะหาเหตุผลได้จริง
    #
    # เดิมส่งไปสองชิ้นต่อหลักสูตร ซึ่งน้อยเกินไปสำหรับหลักสูตรที่เกี่ยวข้องกับคำถามจริงๆ
    # แต่ชิ้นที่ได้คะแนนสูงสุดสองชิ้นแรกดันเป็นข้อความทั่วไปของเล่ม โมเดลจึงตอบว่าไม่มี
    # ข้อมูลรองรับ ทั้งที่เนื้อหาที่ต้องการอยู่ในชิ้นถัดไป ผลคือหลักสูตรที่ควรถูกแนะนำ
    # ถูกคัดออกโดยที่เอกสารมีข้อมูลรองรับอยู่
    _EVIDENCE_CHUNKS, _EVIDENCE_CHARS = 4, 3000
    evidence = [
        {
            "title": s["title"],
            "excerpt": _fetch_evidence(db, s["chunk_ids"][:_EVIDENCE_CHUNKS])[:_EVIDENCE_CHARS],
        }
        for s in scored
    ]
    rationales = _generate_rationales(connector, profile_text, evidence)

    return [
        ProgramMatch(
            course_id=s["course_id"],
            title=s["title"],
            score=round(s["score"], 4),
            match_percent=_to_percent(s["score"]),
            rationale=_rationale_for(rationales, s["title"]),
            evidence_chunk_ids=s["chunk_ids"][:CHUNKS_PER_COURSE],
        )
        for s in scored
    ]


def _generate_rationales(connector, profile_text: str, evidence: list[dict]) -> dict[str, str]:
    """
    ให้โมเดลเขียนเหตุผลของแต่ละหลักสูตร คืน dict ว่างถ้าล้ม

    การจัดอันดับไม่ได้พึ่งขั้นตอนนี้เลย ถ้าโมเดลเรียกไม่ได้หรือตอบผิดรูปแบบ ผู้ใช้ยังได้
    รายการที่เรียงถูกต้องพร้อมเปอร์เซ็นต์ครบ ขาดแค่คำอธิบาย ซึ่งดีกว่าไม่ได้ผลอะไรเลย
    """
    raw = ""
    try:
        raw = connector.chat(
            [
                LLMMessage(role="system", content=MATCH_RATIONALE_SYSTEM_PROMPT),
                LLMMessage(role="user", content=build_match_rationale_prompt(profile_text, evidence)),
            ],
            temperature=0.2,
            json_mode=True,
            # ต้องกำหนดเพดานเอง ไม่ปล่อยให้ใช้ค่าตั้งต้นของผู้ให้บริการ
            #
            # วัดจาก Gemini โดยตรง: ไม่ส่ง maxOutputTokens ไป ได้คำตอบยาวสุด 512 โทเคน
            # ซึ่งไม่พอสำหรับเหตุผลภาษาไทยหกหลักสูตร JSON จึงถูกตัดกลางประโยคแล้วอ่าน
            # ไม่ออก ทำให้เหตุผลหายไปทั้งชุดประมาณครึ่งหนึ่งของการเรียก
            num_predict=connector.answer_token_cap,
        )
        data = json.loads(raw)
        out = {str(k): str(v) for k, v in data.get("rationales", {}).items()}
        if not out:
            # JSON ถูกต้องแต่ไม่มีเนื้อหา — คนละอาการกับเรียกโมเดลไม่ได้ และเป็นอาการ
            # ที่เคยเกิดจริงประมาณหนึ่งในสี่ของการเรียก โดยไม่มีร่องรอยอะไรทิ้งไว้เลย
            logger.warning("เขียนเหตุผลไม่สำเร็จ: คำตอบไม่มีคีย์ rationales — %r", raw[:200])
        return out
    except (LLMConnectionError, json.JSONDecodeError, AttributeError, TypeError) as e:
        # เดิมกลืนข้อยกเว้นเงียบๆ ทำให้เวลาเหตุผลหายไปทั้งชุดไล่หาสาเหตุไม่ได้เลย
        logger.warning("เขียนเหตุผลไม่สำเร็จ (%s) — %r", type(e).__name__, raw[:200])
        return {}


def _rationale_key(title: str) -> str:
    """
    ชื่อหลักสูตรในรูปที่ใช้จับคู่คำตอบของโมเดลกับรายการจริง

    ระบุชื่อปริญญาเป็นคำเต็มทีละคำ ไม่ใช้รูปแบบทั่วไปอย่าง [ก-๙]*บัณฑิต เพราะมันจับ
    แบบตะกละจนกลืนชื่อสาขาไปด้วย (เหตุผลเดียวกับใน services/tuition.py)
    """
    text = re.sub(r"\s*\(.*?\)\s*", "", title)
    text = re.sub(r"(หลักสูตร|สาขาวิชา|สาขา|วิทยาศาสตรบัณฑิต|ศิลปศาสตรบัณฑิต|บัณฑิต)", "", text)
    return text.replace(" ", "").strip()


def _rationale_for(rationales: dict[str, str], title: str) -> str:
    """
    หาเหตุผลของหลักสูตรหนึ่งจากที่โมเดลเขียนมา

    พรอมต์สั่งให้ใช้ชื่อหลักสูตรเป็นคีย์แบบตรงตัวอักษร แต่โมเดลไม่ได้ทำตามเสมอ —
    บางครั้งตัดคำว่า "หลักสูตร" หรือปีในวงเล็บออก การเทียบชื่อแบบตรงตัวอย่างเดียวจึง
    พลาดทั้งชุดในคราวเดียว ผลคือทุกหลักสูตรได้เหตุผลเป็นข้อความว่าง

    วัดจากการเรียกจริงสามรอบด้วยคำถามเดียวกัน หนึ่งรอบคืนคีย์คนละรูปแบบจนว่างทั้ง 6
    รายการ ทั้งที่การจัดอันดับและคะแนนถูกต้องครบ

    เทียบแบบตรงตัวก่อนเสมอ เพราะเมื่อสาขาหนึ่งมีเอกสารสองฉบับ ชื่อที่ตัดปีออกแล้วจะ
    ซ้ำกัน การเทียบแบบหลวมอย่างเดียวจะทำให้ทั้งสองฉบับได้เหตุผลอันเดียวกัน
    """
    if (exact := rationales.get(title)) is not None:
        return exact
    wanted = _rationale_key(title)
    for key, text in rationales.items():
        if _rationale_key(key) == wanted:
            return text
    return ""
