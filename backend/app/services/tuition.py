"""
ค่าเทอม — ข้อมูลที่ไม่ได้อยู่ในเอกสาร มคอ.2

ทำไมต้องแยกออกมาจากคลังเอกสาร
-----------------------------
คำถาม "ค่าเทอมเท่าไหร่" เป็นคำถามที่ผู้ใช้ถามบ่อยที่สุดข้อหนึ่งแต่เอกสาร มคอ.2 ไม่มี
คำตอบ ระบบจึงตอบว่าไม่พบข้อมูลมาตลอด ซึ่งถูกต้องแต่ไม่ช่วยอะไร

ที่แย่กว่านั้นคือครั้งหนึ่งระบบไปหยิบตัวเลข "ค่าใช้จ่ายต่อปีต่อหัว 22,000 บาท" จาก
เอกสารมาตอบ ซึ่งเป็นงบประมาณที่มหาวิทยาลัยใช้ต่อนักศึกษาหนึ่งคน **ไม่ใช่ค่าเทอมที่
นักศึกษาจ่าย** ตัวเลขจริงคือ 12,000 บาท คำตอบนั้นจึงผิดทั้งที่อ้างอิงเอกสารจริง —
เป็นตัวอย่างว่าการอ้างอิงเอกสารได้ไม่ได้แปลว่าคำตอบถูกเสมอไป

ข้อมูลชุดนี้มาจากประกาศของคณะซึ่งเป็นคนละแหล่งกับ มคอ.2 จึงเก็บแยกและระบุที่มา
กำกับทุกครั้งที่นำไปตอบ ผู้ใช้จะได้รู้ว่าข้อมูลส่วนไหนมาจากไหน

ทำไมตอบจากตารางตรงๆ ไม่ผ่านโมเดล
--------------------------------
ค่าเทอมเป็นตัวเลขที่ผิดไม่ได้ การให้โมเดลอ่านแล้วเรียบเรียงใหม่เปิดช่องให้ตัวเลข
เพี้ยนโดยไม่จำเป็น ในเมื่อข้อมูลเป็นตารางที่จับคู่ได้ตรงๆ อยู่แล้ว
"""
from __future__ import annotations

import json
import re
from functools import lru_cache
from pathlib import Path

from app.services.query_expansion import expand_query

_DATA_FILE = Path(__file__).resolve().parent.parent / "data" / "tuition.json"

# คำที่บ่งชี้ว่าผู้ใช้ถามเรื่องค่าเทอม — ตรวจก่อนค้นเอกสารเพื่อลัดไปตอบจากตาราง
_TUITION_WORDS = ("ค่าเทอม", "ค่าเล่าเรียน", "ค่าธรรมเนียมการศึกษา", "ค่าหน่วยกิต", "เทอมละ", "จ่ายเท่าไหร่", "แพงไหม")


@lru_cache(maxsize=1)
def _data() -> dict:
    return json.loads(_DATA_FILE.read_text(encoding="utf-8"))


def is_tuition_question(text: str) -> bool:
    return any(w in text for w in _TUITION_WORDS)


def _normalise(name: str) -> str:
    """
    ตัดคำห่อและช่องว่างออกเพื่อให้เทียบชื่อสาขาข้ามสองแหล่งข้อมูลได้

    ระบุชื่อปริญญาเป็นคำเต็มทีละคำ ไม่ใช้รูปแบบทั่วไปอย่าง [ก-๙]*บัณฑิต เพราะมันจับ
    แบบตะกละจนกลืนชื่อสาขาไปด้วย: "หลักสูตรการแพทย์แผนไทยประยุกต์บัณฑิต" เหลือสตริง
    ว่างทั้งหมด เนื่องจากชื่อสาขากับชื่อปริญญาเป็นคำเดียวกันในหลักสูตรนี้
    """
    name = re.sub(r"\s*\(.*?\)\s*", "", name)
    name = re.sub(r"(หลักสูตร|สาขาวิชา|สาขา|วิทยาศาสตรบัณฑิต|ศิลปศาสตรบัณฑิต|บัณฑิต)", "", name)
    return name.replace(" ", "").strip()


def _variants(name: str) -> list[str]:
    """
    รูปแบบของชื่อสาขาที่ผู้ใช้อาจพิมพ์จริง

    คนไม่พิมพ์คำนำหน้าอย่าง "การ" ที่อยู่ในชื่อทางการ เช่น ตารางเขียนว่า
    "การแพทย์แผนไทยประยุกต์" แต่ผู้ใช้พิมพ์ "แพทย์แผนไทยประยุกต์" ซึ่งไม่ใช่
    สตริงย่อยของกันและกัน จึงต้องเทียบทั้งสองแบบ
    """
    base = _normalise(name)
    out = [base]
    for prefix in ("การ", "วิทยาการ", "เทคโนโลยี", "วิทยาศาสตร์"):
        if base.startswith(prefix) and len(base) > len(prefix) + 3:
            out.append(base[len(prefix):])
    return out


def find_program(text: str, expand: bool = True) -> dict | None:
    """
    หาว่าข้อความถามถึงสาขาใด คืน None ถ้าระบุไม่ได้

    เทียบชื่อยาวก่อนเสมอ เพราะชื่อสั้นบางชื่อเป็นส่วนหนึ่งของชื่อยาว เช่น
    "วิทยาศาสตร์และเทคโนโลยีการอาหาร" มีคำว่า "วิทยาศาสตร์" อยู่ข้างใน

    expand=True สำหรับข้อความที่ผู้ใช้พิมพ์ เพื่อให้ "ไอที" หรือ "วิทคอม" ใช้ได้
    expand=False สำหรับชื่อหลักสูตรเต็มจากฐานข้อมูล ดูเหตุผลใน fee_for()
    """
    target = _normalise(expand_query(text) if expand else text)
    for item in sorted(_data()["programs"], key=lambda p: len(p["name"]), reverse=True):
        if any(v in target for v in _variants(item["name"])):
            return item
    return None


def fee_for(course_title: str) -> dict | None:
    """
    หาค่าเทอมจากชื่อหลักสูตรเต็มในฐานข้อมูล ใช้โดยตารางเปรียบเทียบ

    ปิดการขยายคำย่อไว้โดยตั้งใจ ตารางคำย่อออกแบบมาเพื่อเพิ่มโอกาสค้นเจอตอนผู้ใช้
    พิมพ์สั้นๆ มันจึงเติมชื่อหลักสูตรเต็มเข้าไปในข้อความ ซึ่งพังทันทีเมื่อใช้กับชื่อ
    ที่เจาะจงอยู่แล้ว — "วิทยาศาสตร์และเทคโนโลยีสิ่งแวดล้อม" ถูกจับคู่กับ
    "การจัดการสิ่งแวดล้อมและทรัพยากรธรรมชาติ" ซึ่งเป็นคนละหลักสูตรและค่าเทอมคนละตัว
    """
    return find_program(course_title, expand=False)


def describe(item: dict) -> str:
    """แปลงหนึ่งแถวเป็นข้อความสั้นสำหรับใส่ในตารางเปรียบเทียบ"""
    parts = [f"ภาคปกติ {item['regular']:,} บาท"]
    parts.append(f"ภาคเสาร์-อาทิตย์ {item['weekend']:,} บาท" if item["weekend"] else "ไม่เปิดรับภาคเสาร์-อาทิตย์")
    return " · ".join(parts)


def answer(question: str) -> str:
    """
    ตอบคำถามค่าเทอม ระบุที่มาเสมอเพราะเป็นข้อมูลคนละแหล่งกับที่ระบบใช้ตอบเรื่องอื่น

    ถ้าระบุสาขาไม่ได้ จะไม่เดาให้ แต่บอกวิธีถามใหม่ให้ชัดขึ้น เพราะค่าเทอมต่างกัน
    ระหว่างสาขาจริง (11,000 ถึง 30,000) การตอบค่ากลางๆ ไปจึงทำให้เข้าใจผิด
    """
    data = _data()
    item = find_program(question)
    tail = f"\n\nที่มา: {data['_source']} — {data['_disclaimer']}"

    if item is None:
        names = ", ".join(p["name"] for p in data["programs"][:4])
        return (
            "ค่าเทอมของแต่ละสาขาไม่เท่ากันครับ (ตั้งแต่ 11,000 ถึง 30,000 บาทต่อภาคการศึกษา) "
            f"ลองระบุชื่อสาขาที่สนใจมาด้วย เช่น {names} หรือสาขาอื่นในคณะ" + tail
        )

    lines = [f"สาขา{item['name']} ({item['degree']}) ค่าเทอม{describe(item)}"]
    if item["regular"] >= 20000:
        # ค่าเทอมที่สูงกว่าสาขาอื่นเท่าตัวควรบอกให้ชัด ไม่ให้ผู้ใช้เข้าใจว่าพิมพ์ผิด
        lines.append("สาขานี้มีค่าเทอมสูงกว่าสาขาอื่นในคณะซึ่งส่วนใหญ่อยู่ที่ 12,000 บาท")
    return "\n".join(lines) + tail
