@dataclass(frozen=True)
class Verdict:
    """ผลการตรวจข้ออ้าง — แยกจากการเลือกหน้าโดยสิ้นเชิง"""

    checked: tuple[Claim, ...]

    @property
    def unsupported(self) -> tuple[Claim, ...]:
        return tuple(c for c in self.checked if not c.supported)

    @property
    def status(self) -> str:
        if not self.checked:
            return "ไม่มีข้ออ้างที่ตรวจได้"
        if not self.unsupported:
            return "รองรับครบ"
        if len(self.unsupported) == len(self.checked):
            return "ยืนยันไม่ได้"
        return "รองรับบางส่วน"


def _digit_forms(num: str) -> tuple[str, ...]:
    plain = num.replace(",", "")
    out = {plain}
    if len(plain) > 3:
        out.add(f"{int(plain):,}")
    return tuple(out)


def _norm_forms(forms: Sequence[str]) -> tuple[str, ...]:
    return tuple(dict.fromkeys(
        n for f in forms if (n := normalise(f)) and len(n) >= MIN_NORM))


def _qualifier_of(body: str, at: int) -> tuple[str, str] | None:
    """(คำบอกขั้วตามที่คำตอบเขียน, กลุ่มความหมาย) ของตัวเลขตรงตำแหน่งนี้ — มองย้อนหลังในระยะใกล้"""
    back = body[max(0, at - 28):at]
    found = [(back.rfind(w), w, group)
             for group, words in _POLARITY_WORDS.items() for w in words if w in back]
    if not found:
        return None
    _pos, word, group = max(found)
    return word, group


def claims_of(answer: str) -> tuple[Claim, ...]:
    """ดึงข้ออ้างที่ผิดไม่ได้ออกจากข้อความคำตอบ (ไม่รวมบรรทัดที่มาที่ระบบเติมเอง)"""
    from app.services.answer_evidence import MIN_ITEMS, answer_body, list_items

    body = answer_body(answer)
    all_items = list_items(answer)
    out: list[Claim] = []
    seen: set[tuple[str, str]] = set()

    for index, piece in enumerate(_SEGMENT.split(body)):
        if not piece or not piece.strip():
            continue
        flat = normalise(piece)

        for m in _NUM.finditer(piece):
            num, unit = m.group(1), m.group(2)
            qualifier = _qualifier_of(piece, m.start())
            shown = f"{qualifier[0]} {num} {unit}" if qualifier else f"{num} {unit}"
            key = ("number", shown)
            if key in seen:
                continue
            seen.add(key)
            # ตัวเลขไม่ถูกตัดด้วย normalise จึงเทียบได้ทั้งสองรูป · หน่วยและคำบอกขั้วเป็นเงื่อนไข
            # "ต้องอยู่ใกล้" ไม่ใช่ "มีอยู่ที่ใดก็ได้" เพื่อไม่ให้คำแยกคนละที่ช่วยกันยืนยัน
            out.append(Claim("number", shown, _digit_forms(num), (), index,
                             unit, qualifier[1] if qualifier else None))

        for year in _YEAR.findall(piece):
            key = ("year", year)
            if key in seen:
                continue
            seen.add(key)
            out.append(Claim("year", f"พ.ศ. {year}", (year,), (), index))

        for shown, forms in _DEGREE.items():
            if normalise(shown) in flat:
                key = ("degree", shown)
                if key in seen:
                    continue
                seen.add(key)
                out.append(Claim("degree", shown, tuple(forms), _norm_forms(forms), index))

        # ท่อนที่ไล่รายการ: ใช้ "รายการ" เป็นข้ออ้าง และไม่เพิ่มข้ออ้าง "มี X" ของท่อนนั้นอีก
        #
        # ข้ออ้าง "มี X" ดึง X จากคำที่ตามหลังคำว่า "มี" ซึ่งในประโยคที่ไล่รายการจะได้ข้อความ
        # ปะปน เช่น "มีรายวิชาแคลคูลัสจำนวน" แล้วหาไม่เจอในเอกสาร → รายงานผิดว่ายืนยันไม่ได้
        # ทั้งที่รายการทั้งชุดตรวจได้อยู่แล้ว (วัดจากข้อ r1-05 เมื่อ 15 ต.ค. 2569)
        seg_items = list_items(piece)
        # ประโยคนำของรายการ ("…มีโครงสร้างหลักสูตรแบ่งเป็น 3 หมวดวิชา ดังนี้:") ไม่ใช่ข้ออ้าง
        # ที่ตรวจได้ด้วยตัวเอง — รายการที่ตามมาคือสิ่งที่ต้องตรวจ จึงไม่เพิ่มข้ออ้าง "มี X"
        # ของประโยคนำเมื่อคำตอบมีรายการอยู่จริง (วัดจากข้อ r1-02 เมื่อ 15 ต.ค. 2569)
        leads_list = bool(_LEAD_IN.search(piece)) and len(all_items) >= MIN_ITEMS
        if len(seg_items) >= MIN_ITEMS or leads_list:
            for item in seg_items:
                key = ("item", item)
                if key in seen:
                    continue
                seen.add(key)
                out.append(Claim("item", item, (item,), _norm_forms([item]), ANY_UNIT))
            continue

        for word, term in _EXISTENCE.findall(piece):
            term = term.strip()
            if not any(c in term for c in _CONCRETE) and not any(ch.isdigit() for ch in term):
                continue   # ข้ออ้างเชิงคุณภาพ ไม่ตัดสินด้วยชั้นนี้
            kind = "absence" if word == "ไม่มี" else "existence"
            key = (kind, term)
            if key in seen:
                continue
            seen.add(key)
            forms = [term]
            for classifier in _CLASSIFIERS:
                if term.startswith(classifier) and len(term) - len(classifier) >= 3:
                    forms.append(term[len(classifier):])
                    break
            out.append(Claim(kind, f"{word}{term}", tuple(forms), _norm_forms(forms), index))

    # รายการที่คำตอบไล่ชื่อ — เพิ่มทีเดียวจากคำตอบทั้งก้อน เพราะรายการแบบหัวข้อย่อยอยู่คนละ
    # บรรทัด (คนละท่อน) การเก็บทีละท่อนจะได้ท่อนละหนึ่งชิ้นแล้วไม่เข้าเงื่อนไข "เป็นรายการ"
    # แต่ละรายการตรวจกับหน่วยหลักฐานใดก็ได้ที่คำตอบอ้างถึง (ANY_UNIT) เพราะเป็นข้ออ้างอิสระ
    for item in all_items:
        key = ("item", item)
        if key in seen:
            continue
        seen.add(key)
        out.append(Claim("item", item, (item,), _norm_forms([item]), ANY_UNIT))

    return tuple(out)


class _Unit:
    """หน่วยหลักฐานหนึ่งชิ้น (เนื้อหาหน้าหนึ่งพร้อมชื่อหลักสูตรของหน้านั้น)"""

    __slots__ = ("tight", "norm")

    def __init__(self, text: str) -> None:
        self.tight = re.sub(r"\s+", "", text or "")
        self.norm = normalise(text or "")

    def _has(self, needle: str) -> bool:
        if not needle:
            return False
        if needle in self.tight:
            return True
        n = normalise(needle)
        return bool(n) and len(n) >= MIN_NORM and n in self.norm

    def _near(self, anchor: str, other: str, window: int) -> bool:
        """anchor กับ other ต้องห่างกันไม่เกิน window ตัวอักษรในชิ้นเดียวกัน"""
        for hay, a, b in ((self.tight, anchor, other),
                          (self.norm, normalise(anchor), normalise(other))):
            if not a or not b or a not in hay:
                continue
            if len(b) < MIN_NORM and hay is self.norm:
                continue   # รูปที่ตัดสระแล้วสั้นเกินกว่าจะแยกความหมายได้
            for m in re.finditer(re.escape(a), hay):
                lo = max(0, m.start() - window)
                if b in hay[lo:m.end() + window]:
                    return True
        return False

    def supports(self, c: Claim) -> bool:
        if c.kind == "absence":
            # การไม่พบ X ไม่ใช่หลักฐานว่าไม่มี X — ต้องมีข้อความปฏิเสธเรื่อง X อยู่จริง
            return any(self._near(form, neg, _NEAR_NEGATOR)
                       for form in c.raw for neg in _NEGATORS)
        if c.kind == "item":
            # ใช้กฎเดียวกับตอนเลือกหน้าที่เป็นที่มา (answer_evidence.item_in_flat) เพื่อไม่ให้
            # "หน้าที่ถูกเลือกเป็นที่มา" กับ "รายการที่ยืนยันได้" ขัดกันเอง
            from app.services.answer_evidence import item_in_flat

            return item_in_flat(c.shown, self.norm)
        hit = any(self._has(n) for n in c.raw) or any(n in self.norm for n in c.norm)
        if not hit:
            return False
        # ตัวเลขต้องเกาะกับหน่วยของมันในชิ้นเดียวกัน ไม่ใช่พบตัวเลขที่หนึ่งและหน่วยที่อื่น
        if c.unit and not any(self._near(f, c.unit, _NEAR_UNIT) for f in c.raw):
            return False
        # คำบอกขั้วต้องกำกับตัวเลขนี้จริง · ยอมรับคำอื่นในกลุ่มความหมายเดียวกัน (สรุปความได้)
        # แต่ไม่ยอมข้ามกลุ่ม และไม่ยอมให้คำที่ลอยอยู่คนละข้อของหน้ามานับเป็นของตัวเลขนี้
        if c.polarity:
            words = _POLARITY_WORDS[c.polarity]
            if not any(self._near(f, w, _NEAR_QUALIFIER) for f in c.raw for w in words):
                return False
        return True


# ชนิดข้ออ้างที่เป็น "สาระของคำตอบ" ไม่ใช่ข้อมูลกำกับของเล่ม
#
# ปีและระดับปริญญาเขียนซ้ำแทบทุกหน้าของเล่ม มคอ.2 (หัวตารางเปรียบเทียบ ชื่อเล่ม ท้ายหน้า)
# หน้าที่ไม่มีเรื่องที่ถามอยู่เลยก็ยัง "รองรับ" สองชนิดนี้ได้ จึงใช้ตัดสินความเกี่ยวข้องของหน้า
# ไม่ได้ · วัดจริงเมื่อ 15 ต.ค. 2569: ma64.pdf หน้า 140 (ตารางเปรียบเทียบโครงสร้าง ไม่มีคำว่า
# แคลคูลัสเลย) รองรับข้ออ้าง "พ.ศ. 2564" จากเนื้อหาของหน้าเอง
CONTENT_CLAIMS = frozenset({"number", "item", "existence", "absence"})


def supported_by(answer: str, evidence_texts: Sequence[str]) -> tuple[tuple[Claim, ...], ...]:
    """
    ข้ออ้างที่หลักฐานแต่ละชิ้น "รองรับได้ด้วยตัวเอง" — คืนทูเพิลเรียงตาม evidence_texts

    ตอบคำถามที่ต่างจาก verify()
        verify()       คำตอบนี้มีหลักฐานรองรับหรือไม่ (เลือกหน่วยหลักฐานที่ดีที่สุดหนึ่งชิ้น
                       ต่อหนึ่งท่อน จึงไม่บอกว่าหน้าที่เหลือรองรับอะไรบ้าง)
        supported_by() หน้านี้รองรับสาระของคำตอบหรือไม่ — ใช้ตัดหน้าที่ถูกเลือกมาเพราะ
                       ถ้อยคำซ้ำ แต่ไม่มีเนื้อหาของคำตอบอยู่เลย ออกจากบรรทัดที่มา

    ผู้เรียกต้องส่ง **เนื้อหาของหน้าเท่านั้น** ไม่ต่อชื่อหลักสูตรเข้าไป เพราะชื่อหลักสูตรเป็น
    ข้อมูลกำกับที่ติดอยู่กับทุกหน้าของเล่ม ถ้ารวมเข้าไปด้วย หน้าที่ไม่มีเนื้อหาเกี่ยวกับคำตอบ
    เลยก็ยัง "รองรับ" ข้ออ้างปีหรือระดับปริญญาได้ทุกหน้า · วัดจริงเมื่อ 15 ต.ค. 2569:
    it66.pdf หน้า 137 รองรับข้ออ้าง "พ.ศ. 2566" จากชื่อเล่มที่ต่อท้ายหน่วยหลักฐาน
    ขณะที่เนื้อหาของหน้านั้นไม่รองรับข้ออ้างใดเลย (หน้า 19 รองรับ 6 ข้อ)

    คืนข้ออ้างเป็นก้อน ไม่ใช่เพียงข้อความ เพราะผู้เรียกต้องแยกชนิดที่เป็นสาระออกจาก
    ข้อมูลกำกับของเล่มได้ (ดู CONTENT_CLAIMS)
    """
    claims = claims_of(answer)
    out: list[tuple[Claim, ...]] = []
    for text in evidence_texts:
        unit = _Unit(text or "")
        out.append(tuple(c for c in claims if unit.supports(c)))
    return tuple(out)


def verify(answer: str, evidence_texts: Sequence[str]) -> Verdict:
    """
    ตรวจข้ออ้างของคำตอบกับหลักฐาน — **หนึ่งสมาชิกของ evidence_texts = หนึ่งหน่วยหลักฐาน**

    ผู้เรียกต้องรวมเนื้อหาของชิ้นกับชื่อหลักสูตรของชิ้นนั้นไว้ในสตริงเดียวกัน (ชื่อหลักสูตร
    เป็นข้อมูลกำกับของเอกสาร เช่น "(พ.ศ. 2566)" และ "มหาบัณฑิต" จึงใช้ยืนยันปีและระดับ
    ปริญญาของหน้านั้นได้) และ **ห้ามรวมหลายหน้าเป็นสตริงเดียว** เพราะจะทำให้หลักฐาน
    ของเอกสารหนึ่งไปยืนยันข้ออ้างที่มาจากอีกเอกสารได้

    ข้ออ้างที่อยู่ท่อนเดียวกันของคำตอบต้องถูกรองรับด้วยหน่วยหลักฐานชิ้นเดียวกัน — เลือกชิ้นที่
    รองรับข้ออ้างของท่อนนั้นได้มากที่สุด แล้วตัดสินทุกข้อในท่อนด้วยชิ้นนั้น · คำตอบที่เทียบ
    สองหลักสูตรจึงยังผ่านได้ เพราะแต่ละฝั่งอยู่คนละท่อนและตรวจกับหลักฐานของฝั่งตัวเอง
    """
    units = [_Unit(t) for t in evidence_texts if (t or "").strip()]
    claims = claims_of(answer)
    if not units:
        return Verdict(tuple(Claim(c.kind, c.shown, c.raw, c.norm, c.segment,
                                   c.unit, c.polarity, False) for c in claims))

    checked: list[Claim] = []
    by_segment: dict[int, list[Claim]] = {}
    for c in claims:
        by_segment.setdefault(c.segment, []).append(c)

    for segment, segment_claims in by_segment.items():
        if segment == ANY_UNIT:
            # รายการที่ไล่ชื่อ: รองรับได้ถ้าหน้าใดหน้าหนึ่งที่อ้างถึงมีรายการนั้น
            for c in segment_claims:
                checked.append(Claim(c.kind, c.shown, c.raw, c.norm, c.segment,
                                     c.unit, c.polarity, any(u.supports(c) for u in units)))
            continue
        scored = [(sum(u.supports(c) for c in segment_claims), i)
                  for i, u in enumerate(units)]
        best = units[max(scored)[1]]
        for c in segment_claims:
            checked.append(Claim(c.kind, c.shown, c.raw, c.norm, c.segment,
                                 c.unit, c.polarity, best.supports(c)))
    # คงลำดับเดิมของข้ออ้างไว้ เพื่อให้ข้อความ "ยังยืนยันไม่ได้" อ่านตามลำดับในคำตอบ
    order = {(c.kind, c.shown): i for i, c in enumerate(claims)}
    checked.sort(key=lambda c: order[(c.kind, c.shown)])
    return Verdict(tuple(checked))
