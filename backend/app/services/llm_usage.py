def pending_snapshot() -> dict[tuple[str, str], int]:
    """สำเนาของกองที่ยังไม่ได้เขียน — มีไว้ให้ชุดทดสอบตรวจ ไม่ได้ใช้ตอนทำงานจริง"""
    with _lock:
        return dict(_pending)


def reset_for_test() -> None:
    """
    ล้างสถานะทั้งหมดและหยุดเธรด — ใช้ในชุดทดสอบเท่านั้น

    ล้างกองรอ **ก่อน** รอเธรดจบโดยตั้งใจ เพื่อไม่ให้มีการเขียนฐานข้อมูลหลุดออกไป
    ระหว่างล้าง — ชุดทดสอบคืน SessionLocal ตัวจริงไปแล้วตอนเรียกตัวนี้
    """
    global _fail_streak, _worker, _last_flush
    _stop.set()
    with _lock:
        worker, _worker = _worker, None
        _pending.clear()
        _fail_streak = 0
        _last_flush = time.monotonic()
    if worker is not None:
        worker.join(EXIT_FLUSH_TIMEOUT_S)


