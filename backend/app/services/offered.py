"""
หลักสูตรที่คณะเปิดรับสมัครอยู่จริง เทียบจากหน้าหลักสูตรของเว็บไซต์คณะ

ทำไมต้องแยกจาก "หลักสูตรที่มีเอกสารในคลัง"
------------------------------------------
คลังเก็บเอกสารทุกฉบับที่ได้มา ซึ่งรวมทั้งฉบับปรับปรุงใหม่และฉบับก่อนหน้าของหลักสูตร
เดียวกัน และหลักสูตรที่เลิกรับสมัครไปแล้วแต่เอกสารยังอยู่ ผลคือระบบรู้จัก 16 หลักสูตร
ระดับปริญญาตรี ขณะที่เว็บไซต์คณะแสดง 12

ส่วนต่างสี่หลักสูตรไม่ใช่เรื่องเล็ก ระบบนี้มีหน้าที่บอกนักเรียนว่าควรเรียนที่ไหน
การเสนอหลักสูตรที่ไม่เปิดรับแล้วทำให้เขาวางแผนไปสมัครในสิ่งที่ไม่มีอยู่ ซึ่งเสียหาย
กว่าการไม่เสนออะไรเลย

เก็บเป็นรายการที่คนตรวจแล้ว ไม่ใช่เดาจากปีในชื่อ
------------------------------------------------
เดิมระบบยุบฉบับต่างปีของหลักสูตรเดียวกันด้วยการเทียบชื่อ ซึ่งใช้ได้เมื่อชื่อไม่เปลี่ยน
แต่คณะเปลี่ยนชื่อหลักสูตรตอนปรับปรุงด้วย เช่น "วิทยาศาสตร์และเทคโนโลยีการอาหาร"
กลายเป็น "เทคโนโลยีอาหารและความเป็นผู้ประกอบการสมัยใหม่" การเทียบชื่อจึงมองเป็นคนละ
หลักสูตรและแสดงทั้งคู่ ไม่มีกฎอัตโนมัติใดบอกได้ว่าสองชื่อนี้คือหลักสูตรเดียวกัน
ต้องอ่านจากประกาศของคณะเท่านั้น
"""
from __future__ import annotations

import json
import logging
from functools import lru_cache
from pathlib import Path

from app.services.course_scope import _distinctive_name

logger = logging.getLogger("course_advisor")

_DATA = Path(__file__).resolve().parents[1] / "data" / "programs_offered.json"


@lru_cache(maxsize=1)
def _offered() -> tuple[set[str], set[str]]:
    raw = json.loads(_DATA.read_text(encoding="utf-8"))
    return set(raw["undergraduate"]), set(raw["graduate"])


def is_offered(course_title: str) -> bool:
    """หลักสูตรนี้ยังอยู่ในรายการที่คณะเปิดสอนหรือไม่"""
    under, grad = _offered()
    return _distinctive_name(course_title) in under | grad


def offered_undergraduate() -> set[str]:
    return _offered()[0]


def offered_graduate() -> set[str]:
    return _offered()[1]


_warned = False


def warn_on_name_mismatch(titles: list[str]) -> None:
    """
    เตือนเมื่อชื่อในไฟล์ไม่ตรงกับชื่อหลักสูตรใดในคลังเลย

    ชื่อในไฟล์ต้องตรงกับชื่อที่ _distinctive_name() ตัดออกมาจากชื่อหลักสูตรจริงทุกตัวอักษร
    ถ้าพิมพ์ต่างไปแม้คำเดียว หลักสูตรนั้นจะหายจากรายการเงียบๆ โดยไม่มีอะไรฟ้อง

    เกิดขึ้นแล้วจริงตอนสร้างไฟล์นี้ครั้งแรก: หน้าเว็บคณะพาดหัวการ์ดว่า "เทคโนโลยี
    การเกษตรสมัยใหม่" แต่ชื่อหลักสูตรในเอกสารคือ "การจัดการเทคโนโลยีการเกษตรสมัยใหม่"
    รายการจึงแสดง 11 สาขาแทนที่จะเป็น 12 — ซึ่งเป็นความผิดพลาดชนิดที่มองไม่เห็นถ้าไม่
    ไล่นับทีละบรรทัด เพราะผลลัพธ์ยังดูสมเหตุสมผลทุกประการ

    เตือนครั้งเดียวต่อโปรเซส เพราะเรียกทุกครั้งที่มีคนถามรายชื่อหลักสูตร
    """
    global _warned
    if _warned:
        return
    _warned = True
    known = {_distinctive_name(t) for t in titles}
    for name in offered_undergraduate() | offered_graduate():
        if name not in known:
            logger.warning(
                "programs_offered.json มีชื่อ %r ที่ไม่ตรงกับหลักสูตรใดในคลัง "
                "— หลักสูตรนั้นจะหายไปจากรายการที่แสดงให้ผู้ใช้",
                name,
            )
