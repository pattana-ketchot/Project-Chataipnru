import sys
import unittest
from dataclasses import dataclass
from pathlib import Path

sys.stdout.reconfigure(encoding="utf-8", errors="replace")
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from app.services.answer_evidence import answer_body, quote_is_supported, supporting


@dataclass
class FakeChunk:
    chunk_id: str
    course_id: str
    course_title: str
    page_number: int
    content: str
    score: float


IT_TITLE = "หลักสูตรวิทยาศาสตรบัณฑิต สาขาวิชาเทคโนโลยีสารสนเทศ (พ.ศ. 2566)"
# ข้อความจริงจาก it66.pdf หน้า 16 §2.2 (ตัดมา) และหน้า 161 (ภาคผนวกข้อบังคับ)
PAGE_16 = ("2.2 คุณสมบัติของผู้เข้าศึกษา 2.2.1 ผู้สำเร็จการศึกษาระดับมัธยมศึกษาตอนปลายหรือเทียบเท่า "
           "หรือเป็นไปตามประกาศ ระเบียบ และข้อบังคับของมหาวิทยาลัยราชภัฏพระนคร "
           "2.2.2 ผู้สำเร็จการศึกษาระดับประกาศนียบัตรวิชาชีพชั้นสูง (ปวส.) หรือเทียบเท่าในสาขาทางด้าน"
           "คอมพิวเตอร์ทุกสาขา 2.2.3 ผู้สำเร็จการศึกษาระดับปริญญาตรี โดยมีคุณสมบัติเป็นไปตามข้อบังคับ")
PAGE_161 = ("หมวดที่ 1 การรับเข้าศึกษา ข้อ 5 ผู้มีสิทธิสมัครเข้าเป็นนักศึกษา 5.1 คุณสมบัติของผู้สมัคร "
            "5.1.1 ไม่เคยรับโทษจำคุกโดยคำพิพากษาถึงที่สุดให้จำคุก เว้นแต่ความผิดที่กระทำโดยประมาท")
REPLY_IT = ("คุณสมบัติผู้เข้าศึกษาหลักสูตรวิทยาศาสตรบัณฑิต สาขาวิชาเทคโนโลยีสารสนเทศ ได้แก่ "
            "ผู้สำเร็จการศึกษาระดับมัธยมศึกษาตอนปลายหรือเทียบเท่า หรือเป็นไปตามประกาศ ระเบียบ "
            "และข้อบังคับของมหาวิทยาลัยราชภัฏพระนคร นอกจากนี้ยังรับผู้สำเร็จการศึกษาระดับ "
            "ประกาศนียบัตรวิชาชีพชั้นสูง (ปวส.) หรือเทียบเท่าในสาขาทางด้านคอมพิวเตอร์ทุกสาขา "
            "และผู้สำเร็จการศึกษาระดับปริญญาตรี")


class EvidenceTests(unittest.TestCase):
    def test_picks_the_page_that_supports_not_the_top_score(self):
        chunks = [
            FakeChunk("c161", "it", IT_TITLE, 161, PAGE_161, 0.706),   # คะแนนสูงสุด
            FakeChunk("c16", "it", IT_TITLE, 16, PAGE_16, 0.614),
        ]
        picked = supporting(REPLY_IT, chunks, "คุณสมบัติผู้เข้าศึกษาของเทคโนโลยีสารสนเทศคืออะไร")
        self.assertTrue(picked, "ต้องเลือกหลักฐานได้")
        self.assertEqual(picked[0].page_number, 16, "ต้องเลือกหน้า 16 ไม่ใช่หน้า 161 ที่คะแนนสูงกว่า")
        self.assertNotIn(161, [p.page_number for p in picked])

    def test_multiple_documents_when_the_answer_spans_two(self):
        cs = "ปรัชญา มุ่งผลิตบัณฑิตที่มีความรู้ด้านวิทยาการคอมพิวเตอร์ที่ทันสมัย มีทักษะในการประยุกต์ใช้"
        it = "ปรัชญา ผลิตบัณฑิตด้านเทคโนโลยีสารสนเทศที่มีความรู้ความเชี่ยวชาญ ตอบสนองแรงงานในยุคดิจิทัล"
        reply = ("วิทยาการคอมพิวเตอร์มุ่งผลิตบัณฑิตที่มีความรู้ด้านวิทยาการคอมพิวเตอร์ที่ทันสมัย "
                 "มีทักษะในการประยุกต์ใช้ ส่วนเทคโนโลยีสารสนเทศผลิตบัณฑิตด้านเทคโนโลยีสารสนเทศ"
                 "ที่มีความรู้ความเชี่ยวชาญ ตอบสนองแรงงานในยุคดิจิทัล")
        chunks = [
            FakeChunk("a", "cs", "หลักสูตร...วิทยาการคอมพิวเตอร์ (พ.ศ. 2566)", 10, cs, 0.5),
            FakeChunk("b", "it", IT_TITLE, 12, it, 0.49),
        ]
        picked = supporting(reply, chunks, "วิทยาการคอมพิวเตอร์กับเทคโนโลยีสารสนเทศต่างกันอย่างไร")
        self.assertEqual({p.page_number for p in picked}, {10, 12},
                         "คำตอบที่สังเคราะห์จากสองเล่มต้องได้ที่มาทั้งสองเล่ม")

    def test_no_evidence_returns_empty_not_a_guess(self):
        chunks = [FakeChunk("x", "it", IT_TITLE, 99, "ตารางงบประมาณตามแผน หมวดเงินเดือน", 0.9)]
        picked = supporting("หลักสูตรนี้มีทุนการศึกษาสำหรับนักศึกษาชั้นปีที่ 1 จำนวน 20 ทุน", chunks, "มีทุนไหม")
        self.assertEqual(picked, (), "ไม่มีหลักฐานต้องคืนค่าว่าง ไม่ใช่เดาหน้าให้")

    def test_source_line_is_not_treated_as_answer_content(self):
        self.assertNotIn("ที่มา", answer_body("คำตอบ\n\nที่มา: cs66.pdf หน้า 16"))
        self.assertIn("คำตอบ", answer_body("คำตอบ\n\nที่มา: cs66.pdf หน้า 16"))

    def test_quote_must_come_from_that_programmes_evidence(self):
        self.assertTrue(quote_is_supported("ความรู้ความเชี่ยวชาญ ตอบสนองแรงงานในยุคดิจิทัล",
                                           "ผลิตบัณฑิตด้านเทคโนโลยีสารสนเทศที่มีความรู้ความเชี่ยวชาญ ตอบสนองแรงงานในยุคดิจิทัล"))
        self.assertFalse(quote_is_supported("ภาคทฤษฎีและปฏิบัติเพื่อพัฒนานวัตกรรมทางคอมพิวเตอร์",
                                            "มุ่งผลิตบัณฑิตที่มีความรู้ด้านวิทยาการคอมพิวเตอร์ที่ทันสมัย"),
                         "ถ้อยคำที่ไม่อยู่ในเอกสารของสาขานั้นต้องไม่ผ่าน")
        self.assertFalse(quote_is_supported("สั้นไป", "ข้อความยาวที่มีคำว่าสั้นไปอยู่ด้วย"),
                         "ข้อความสั้นเกินไปไม่ถือเป็นหลักฐาน")


if __name__ == "__main__":
    unittest.main(verbosity=2)
