# ล็อกอินแล้วยังได้ 422 ต่ออีก เพราะส่งเนื้อความผิดรูปแบบ ทั้งสองรอบรายงานออกมาว่า
# "เรียก API ไม่สำเร็จ" ซึ่งอ่านแล้วเหมือนระบบพัง ทั้งที่ระบบปกติดีและตัวตรวจเองเข้า
# ไม่ถูกประตู — ชุดตรวจที่ฟ้องผิดที่แบบนี้อันตรายกว่าไม่มีเลย เพราะจะถูกเมินในวันที่
# มันจับของจริงได้
_WEB_STYLE = lambda q: {"messages": [{"role": "user", "content": q}]}
_API_STYLE = lambda q: {"message": q}


def configure(client: httpx.Client):
    """
    หาว่าปลายทางนี้ต้องล็อกอินไหม และรับเนื้อความรูปแบบไหน คืนฟังก์ชันสำหรับถาม

    ตรวจด้วยการยิงจริงแล้วดูว่าเซิร์ฟเวอร์ตอบอะไร ไม่ใช่เดาจากรูปแบบ URL เพราะ URL
    เปลี่ยนได้ แต่สิ่งที่เซิร์ฟเวอร์ตอบคือความจริง
    """
    probe = client.post("/chat", json=_WEB_STYLE("สวัสดี"))

    if probe.status_code == 401:
        email = f"behaviour-{secrets.token_hex(4)}@example.com"
        client.post("/auth/register", json={"email": email, "password": "password123"})
        r = client.post("/auth/login", json={"email": email, "password": "password123"})
        r.raise_for_status()
        client.headers["Authorization"] = f"Bearer {r.json()['access_token']}"
        print("ปลายทางต้องล็อกอิน สร้างบัญชีชั่วคราวให้แล้ว")
        probe = client.post("/chat", json=_WEB_STYLE("สวัสดี"))

    # 422 = รับเนื้อความคนละรูปแบบ ไม่ใช่ระบบพัง
    build = _WEB_STYLE
    if probe.status_code == 422:
        confirm = client.post("/chat", json=_API_STYLE("สวัสดี"))
        confirm.raise_for_status()
        build = _API_STYLE
        print("ปลายทางรับคำถามแบบ message เดี่ยว")

    elif probe.status_code >= 400:
        raise SystemExit(f"ปลายทางตอบ HTTP {probe.status_code} ตั้งแต่คำถามทดลอง: {probe.text[:200]}")

    print()

    def ask(client: httpx.Client, question: str) -> str:
        r = client.post("/chat", json=build(question))
        r.raise_for_status()
        # ตรวจเฉพาะข้อความที่ผู้ใช้เห็น ไม่ใช่ทั้งก้อน JSON
        #
        # เดิมคืน r.text ทั้งก้อน ซึ่งการตรวจแบบหาคำยังทำงานได้ จึงไม่มีใครสังเกต แต่
        # ข้อที่ต้องนับบรรทัดพังเงียบๆ เพราะใน JSON ขึ้นบรรทัดใหม่ถูกเขียนเป็น \\n
        # สองอักขระ ทั้งคำตอบจึงเป็นบรรทัดเดียว นับรายการได้ 0 ข้อเสมอ แล้วรายงานว่า
        # ตอบมา 0 อาชีพ ทั้งที่ตอบมาครบ — ชุดตรวจกล่าวหาระบบในสิ่งที่ระบบไม่ได้ทำ
        #
        # อีกเหตุผลคือชื่อฟิลด์อย่าง session_id หรือข้อความที่ระบบใส่มาในซองอาจไป
        # ตรงกับคำที่กำลังหา ทำให้ตัดสินจากสิ่งที่ผู้ใช้ไม่เคยเห็น
        try:
            body = r.json()
        except ValueError:
            return r.text
        return body.get("reply", r.text) if isinstance(body, dict) else r.text

    return ask


def main() -> None:
    ap = argparse.ArgumentParser(description="ตรวจพฤติกรรมที่เคยพังมาแล้ว")
    ap.add_argument("--api", default="https://stpnru-advisor.duckdns.org/api")
    args = ap.parse_args()

    checks = build_checks()
    client = httpx.Client(base_url=args.api, timeout=180)
    ask = configure(client)
    failed = []
    skipped: list[Check] = []

    print(f"ตรวจ {len(checks)} ข้อ ที่ {args.api}\n")
    for i, c in enumerate(checks, 1):
        t0 = time.time()
        try:
            reply = ask(client, c.ask)
        except httpx.TimeoutException:
            # รอเกิน 180 วินาทีแล้วยังไม่ได้คำตอบ ถือว่าตรวจข้อนี้ไม่ได้ ไม่ใช่ตก
            # เพราะยังไม่เห็นคำตอบจึงยังไม่รู้ว่าพฤติกรรมถูกหรือผิด สาเหตุที่พบบ่อย
            # คือตกไปใช้โมเดลในเครื่องซึ่งช้ามากบนเครื่องที่ไม่มีการ์ดจอ แต่ยืนยัน
            # จากตรงนี้ไม่ได้ ต้องดู log ของ backend
            skipped.append(c)
            print(f"  ข้าม [{i}/{len(checks)}] {c.name}  (หมดเวลารอ ระบบตอบช้าผิดปกติ)")
            continue
        except Exception as e:
            failed.append((c, [f"เรียก API ไม่สำเร็จ: {type(e).__name__}"], ""))
            print(f"  พัง  [{i}/{len(checks)}] {c.name}")
            continue
        if any(d in reply for d in DEGRADED):
            # ระบบตอบแบบลดทอนอยู่ ตรวจข้อนี้ไม่ได้ ซึ่งไม่เหมือนกับตก
            skipped.append(c)
            print(f"  ข้าม [{i}/{len(checks)}] {c.name}  (ระบบทำงานแบบลดทอนอยู่)")
            continue
        problems = c.verify(reply)
        mark = "ผ่าน" if not problems else "ตก "
        print(f"  {mark} [{i}/{len(checks)}] {c.name}  ({time.time() - t0:.1f}s)")
        if problems:
            failed.append((c, problems, reply))

    tested = len(checks) - len(skipped)
    print("\n" + "=" * 70)
    if skipped:
        # ไม่บอกสาเหตุตรงนี้ เพราะสคริปต์นี้เห็นแค่ข้อความที่ผู้ใช้ได้รับ ซึ่งไม่ได้
        # แยกแยะว่าเบื้องหลังเกิดอะไร ข้อความ "ระบบหลักตอบไม่ได้ชั่วคราว" เดียวกันนี้
        # เกิดได้ทั้งจากโควตาหมด จากการอ่านคำตอบเป็น JSON ไม่สำเร็จ (เจอจริง: Gemini
        # ตอบ HTTP 200 แล้ว JSONDecodeError ในขั้นเขียนเหตุผล) และจากการต่อไม่ติด
        # เคยเขียนไว้ว่า "โควตาของโมเดลหลักน่าจะหมด" แล้วมีคนอ่านเชื่อตามนั้นไปตรวจ
        # ผิดที่ — การเดาสาเหตุแล้วพิมพ์ออกมาเหมือนข้อเท็จจริงแพงกว่าการไม่บอกเลย
        print(f"ตรวจไม่ได้ {len(skipped)} ข้อ เพราะระบบตอบแบบลดทอน "
              "ต้องรันซ้ำเมื่อกลับมาปกติ และดู log ของ backend เพื่อหาสาเหตุจริง")
        for c in skipped:
            print(f"    - {c.name}")
        print()
    if not failed:
        print(f"ผ่านครบ {tested} ข้อที่ตรวจได้")
        sys.exit(2 if skipped else 0)

    print(f"ตก {len(failed)} จาก {tested} ข้อที่ตรวจได้\n")
    for c, problems, reply in failed:
        print(f"[{c.name}]")
        print(f"  ถาม: {c.ask}")
        for p in problems:
            print(f"  ปัญหา: {p}")
        print(f"  ข้อนี้มีเพราะ: {c.why}")
        print(f"  คำตอบที่ได้: {reply[:300].strip()}")
        print()
    sys.exit(1)


if __name__ == "__main__":
    main()
