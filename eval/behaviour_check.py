from __future__ import annotations

import argparse
import sys
import time

import httpx

# หลักสูตรที่คณะเปิดสอน ตรงกับ backend/app/data/programs_offered.json
OFFERED = [
    "การจัดการสิ่งแวดล้อมและทรัพยากรธรรมชาติ",
    "การจัดการเทคโนโลยีการเกษตรสมัยใหม่",
    "การประกอบอาหารและการบริการอาหาร",
    "การแพทย์แผนไทยประยุกต์",
    "คณิตศาสตร์",
    "คอมพิวเตอร์แอนิเมชันและมัลติมีเดีย",
    "วิทยาการคอมพิวเตอร์",
    "วิทยาศาสตร์เครื่องสำอาง",
    "สาธารณสุขศาสตร์",
    "เทคโนโลยีผลิตภัณฑ์ชีวภาพกับการประกอบธุรกิจ",
    "เทคโนโลยีสารสนเทศ",
    "เทคโนโลยีอาหารและความเป็นผู้ประกอบการสมัยใหม่",
]

# หลักสูตรที่มีเอกสารในคลังแต่คณะไม่ได้เปิดสอนแล้ว ห้ามโผล่ในคำแนะนำหรือรายชื่อ
WITHDRAWN = [
    "คหกรรมศาสตร์",
    "เทคโนโลยีการจัดการสุขภาพ",
    "วิทยาศาสตร์และเทคโนโลยีการอาหาร",
    "วิทยาศาสตร์และเทคโนโลยีสิ่งแวดล้อม",
]

# ข้อความภายในระบบที่ต้องไม่หลุดไปถึงผู้ใช้
LEAKS = ["[[ไม่มีข้อมูลรองรับ]]", "[[อ่านไม่ออก]]", "COURSE_CONTENT"]

# สัญญาณว่าระบบกำลังทำงานแบบลดทอนอยู่ ไม่ใช่ว่าพฤติกรรมเปลี่ยนไป
#
# ต้องแยกสองอย่างนี้ออกจากกัน ไม่งั้นชุดตรวจจะรายงานว่าตกทุกครั้งที่โควตาหมด แล้ว
# คนอ่านจะเริ่มเมินผลของมัน ซึ่งทำให้ชุดตรวจไร้ประโยชน์ในวันที่มันจับของจริงได้
DEGRADED = [
    "ระบบหลักตอบไม่ได้ชั่วคราว",
    "ยังเขียนคำอธิบายประกอบให้ไม่ได้",
    "ระบบตอบไม่ได้ในขณะนี้",
]


class Check:
    """หนึ่งข้อตรวจ พร้อมเหตุผลว่าทำไมถึงมีข้อนี้"""

    def __init__(self, name, ask, why, verify):
        self.name, self.ask, self.why, self.verify = name, ask, why, verify


def _count_listed(reply: str) -> int:
    """จำนวนบรรทัดที่เป็นรายการ ทั้งแบบ - และแบบเลขนำหน้า"""
    n = 0
    for line in reply.splitlines():
        s = line.strip()
        if s.startswith("-") or (len(s) > 2 and s[0].isdigit() and s[1] in ".)"):
            n += 1
    return n


def build_checks() -> list[Check]:
    def has_all(*words):
        return lambda r: [w for w in words if w not in r] or None

    def has_none(*words):
        return lambda r: [f"พบ {w}" for w in words if w in r] or None

    checks: list[Check] = []

    # --- รายชื่อหลักสูตร (ไม่ผ่านโมเดล ไม่ถูกแคช) ---
    def list_is_exact(r):
        problems = [f"ขาด {p}" for p in OFFERED if p not in r]
        problems += [f"มีหลักสูตรที่ปิดแล้ว {p}" for p in WITHDRAWN if p in r]
        return problems or None

    checks.append(Check(
        "รายชื่อหลักสูตรครบและไม่มีที่ปิดแล้ว",
        "คณะมีสาขาอะไรบ้าง",
        "เคยแสดง 11 สาขาแทนที่จะเป็น 12 เพราะชื่อในไฟล์ต่างจากในเอกสารคำเดียว "
        "และเคยแสดงหลักสูตรที่คณะเลิกเปิดสอนแล้วสี่หลักสูตร",
        list_is_exact,
    ))

    # --- ความครบถ้วนของรายการที่เอกสารแจกแจงไว้ ---
    # จำนวนที่คาดหวังนับจากเอกสารจริง (มคอ.2 หัวข้อ 8 อาชีพที่สามารถประกอบได้)
    checks.append(Check(
        "รายการอาชีพครบตามเอกสาร",
        "สาขาวิทยาการคอมพิวเตอร์จบไปทำอาชีพอะไรได้บ้าง",
        "เคยตอบมา 5 อาชีพ ทั้งที่เอกสารระบุ 8 ข้อ (ฉบับ 2561) และ 9 ข้อ (ฉบับ 2566) "
        "โดยไม่มีอะไรบอกผู้อ่านว่ายังมีข้ออื่น — สาเหตุคือกฎในพรอมต์ที่จำกัดรายการไว้ 5 ข้อ",
        lambda r: None if _count_listed(r) >= 8 else [f"ได้ {_count_listed(r)} ข้อ ควรได้อย่างน้อย 8"],
    ))

    # --- การแนะนำสาขา: ต้องตรงกับแก่นของหลักสูตร ---
    checks.append(Check(
        "แนะนำสาขาตามแก่นของหลักสูตร ไม่ใช่เครื่องมือที่ใช้",
        "สาขาไหนเหมาะกับคนชอบทำงานกับคอมพิวเตอร์",
        "เคยแนะนำการประกอบอาหารและการบริการอาหาร เพราะหลักสูตรนั้นมีวิชาใช้คอมพิวเตอร์ "
        "ในงานบริการ — คอมพิวเตอร์เป็นเครื่องมือของหลักสูตรนั้น ไม่ใช่แก่นของมัน",
        lambda r: (has_all("วิทยาการคอมพิวเตอร์", "เทคโนโลยีสารสนเทศ")(r) or [])
        + (has_none("การประกอบอาหาร")(r) or []) or None,
    ))

    checks.append(Check(
        "ไม่เติมสาขาให้ครบสามเมื่อมีสาขาเดียวที่ตรง",
        "สาขาไหนเหมาะกับคนชอบคำนวณและตัวเลข",
        "เคยแสดงสามอันดับเสมอ อันดับ 2 และ 3 จึงเป็นสาขาที่บังเอิญมีคำตรงกันในเอกสาร",
        lambda r: None if _count_listed(r) <= 2 else [f"แนะนำมา {_count_listed(r)} สาขา ควรไม่เกิน 2"],
    ))

    def no_withdrawn(r):
        return [f"เสนอหลักสูตรที่ปิดแล้ว {p}" for p in WITHDRAWN if p in r] or None

    checks.append(Check(
        "ไม่เสนอหลักสูตรที่คณะเลิกเปิดสอน",
        "สาขาไหนเหมาะกับคนชอบทำอาหารและงานบ้าน",
        "เคยเสนอคหกรรมศาสตร์เป็นอันดับหนึ่ง ซึ่งไม่อยู่ในรายการหลักสูตรของคณะแล้ว "
        "นักเรียนอาจวางแผนไปสมัครในสิ่งที่ไม่มีอยู่",
        no_withdrawn,
    ))

    checks.append(Check(
        "คำแนะนำไม่มีเปอร์เซ็นต์และไม่มีข้อความว่าข้อมูลไม่พอ",
        "สาขาไหนเหมาะกับคนชอบทำงานด้านบริการ",
        "ตัวเลขอย่าง 71% ชวนให้อ่านเป็นความน่าจะเป็นที่จะเรียนได้ดี ซึ่งไม่ใช่สิ่งที่วัด "
        "และเคยแสดงสาขาที่ใต้ชื่อเขียนว่าข้อมูลไม่เพียงพอ ซึ่งขัดกันเอง",
        lambda r: ([f"พบเปอร์เซ็นต์"] if any(f"{i}%" in r for i in range(101)) else [])
        + (has_none("ไม่เพียงพอ", *LEAKS)(r) or []) or None,
    ))

    # --- ถามกลับเมื่อคำถามไม่ระบุสาขา ---
    checks.append(Check(
        "ถามกลับเมื่อคำถามไม่ได้บอกว่าสาขาไหน",
        "เรียนจบแล้วทำอาชีพอะไรได้บ้าง",
        "เคยไปหยิบสาขาหนึ่งมาตอบเงียบๆ โดยผู้อ่านไม่มีทางรู้ว่าระบบเลือกให้เอง "
        "แล้วเข้าใจว่านั่นคืออาชีพของทั้งคณะ",
        has_all("สาขาไหน"),
    ))

    # --- แยก "ไม่มีข้อมูล" ออกจาก "นอกขอบเขต" ---
    checks.append(Check(
        "คำถามในขอบเขตที่เอกสารไม่มีข้อมูล ต้องไม่ถูกปฏิเสธว่านอกเรื่อง",
        "สาขาสาธารณสุขศาสตร์มีวิชาบังคับอะไรบ้าง",
        "เคยตอบว่า 'ผมตอบได้เฉพาะเรื่องหลักสูตร' กับคำถามเรื่องหลักสูตรตรงๆ เพราะ "
        "ตัวคัดกรองอ่านคำว่าสาธารณสุขเป็นเรื่องสุขภาพ ไม่ใช่เรื่องมหาวิทยาลัย",
        has_none("ตอบได้เฉพาะเรื่องหลักสูตร"),
    ))

    # --- guardrail ต้องยังทำงาน ---
    for q in ("วันนี้อากาศเป็นยังไง", "ช่วยเขียนโค้ด python ให้หน่อย"):
        checks.append(Check(
            f"ปฏิเสธคำถามนอกเรื่อง: {q}",
            q,
            "การผ่อนเกณฑ์เพื่อให้ตอบคำถามในขอบเขตได้มากขึ้น อาจทำให้ guardrail หลวมตามไปด้วย",
            has_all("ตอบได้เฉพาะเรื่องหลักสูตร"),
        ))

    return checks


def ask(client: httpx.Client, question: str) -> str:
    r = client.post("/chat", json={"messages": [{"role": "user", "content": question}]})
    r.raise_for_status()
    return r.text


def main() -> None:
    ap = argparse.ArgumentParser(description="ตรวจพฤติกรรมที่เคยพังมาแล้ว")
    ap.add_argument("--api", default="https://stpnru-advisor.duckdns.org/api")
    args = ap.parse_args()

    checks = build_checks()
    client = httpx.Client(base_url=args.api, timeout=180)
    failed = []
    skipped: list[Check] = []

    print(f"ตรวจ {len(checks)} ข้อ ที่ {args.api}\n")
    for i, c in enumerate(checks, 1):
        t0 = time.time()
        try:
            reply = ask(client, c.ask)
        except httpx.TimeoutException:
            # หมดเวลารอแปลว่ากำลังตอบด้วยโมเดลในเครื่องซึ่งช้ามากบนเครื่องที่ไม่มี
            # การ์ดจอ เป็นสภาพลดทอนเหมือนกัน ไม่ใช่พฤติกรรมที่เปลี่ยนไป
            skipped.append(c)
            print(f"  ข้าม [{i}/{len(checks)}] {c.name}  (หมดเวลารอ ระบบตอบช้าผิดปกติ)")
            continue
        except Exception as e:
            failed.append((c, [f"เรียก API ไม่สำเร็จ: {type(e).__name__}"], ""))
            print(f"  พัง  [{i}/{len(checks)}] {c.name}")
            continue
        if any(d in reply for d in DEGRADED):
            # ระบบตอบแบบลดทอนอยู่ ตรวจข้อนี้ไม่ได้ ซึ่งไม่เหมือนกับตก
            skipped.append(c)
            print(f"  ข้าม [{i}/{len(checks)}] {c.name}  (ระบบทำงานแบบลดทอนอยู่)")
            continue
        problems = c.verify(reply)
        mark = "ผ่าน" if not problems else "ตก "
        print(f"  {mark} [{i}/{len(checks)}] {c.name}  ({time.time() - t0:.1f}s)")
        if problems:
            failed.append((c, problems, reply))

    tested = len(checks) - len(skipped)
    print("\n" + "=" * 70)
    if skipped:
        print(f"ตรวจไม่ได้ {len(skipped)} ข้อ เพราะระบบตอบแบบลดทอน "
              "(โควตาของโมเดลหลักน่าจะหมด) ต้องรันซ้ำเมื่อกลับมาปกติ")
        for c in skipped:
            print(f"    - {c.name}")
        print()
    if not failed:
        print(f"ผ่านครบ {tested} ข้อที่ตรวจได้")
        sys.exit(2 if skipped else 0)

    print(f"ตก {len(failed)} จาก {tested} ข้อที่ตรวจได้\n")
    for c, problems, reply in failed:
        print(f"[{c.name}]")
        print(f"  ถาม: {c.ask}")
        for p in problems:
            print(f"  ปัญหา: {p}")
        print(f"  ข้อนี้มีเพราะ: {c.why}")
        print(f"  คำตอบที่ได้: {reply[:300].strip()}")
        print()
    sys.exit(1)


if __name__ == "__main__":
    main()
